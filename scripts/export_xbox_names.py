"""Export accepted Xbox CSV names without changing codegen or hook behavior.

Inputs: docs/native-port/data/xbox-names.csv and .cache/pvz-image.bin.
Outputs: src/xbox_names.h, research/cross-platform/xbox-names.ghidra.py,
and an ignored JSON manifest. Both exports embed SHA-256 of both inputs.
High and medium names retain their confidence and evidence. Overloaded names
receive a suffix derived from the complete argument signature; no re-scoring.
Run with Python 3.10+ (python -I scripts/export_xbox_names.py); --check only
compares regenerated bytes. The generated script is Jython/PyGhidra compatible.
"""

from __future__ import annotations

import argparse
from collections import Counter
import csv
import hashlib
import io
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BASE = 0x82000000
CPP_KEYWORDS = set("""alignas alignof and and_eq asm auto bitand bitor bool break
case catch char char8_t char16_t char32_t class compl concept const consteval
constexpr constinit const_cast continue co_await co_return co_yield decltype
default delete do double dynamic_cast else enum explicit export extern false
float for friend goto if inline int long mutable namespace new noexcept not
not_eq nullptr operator or or_eq private protected public register reinterpret_cast
requires return short signed sizeof static static_assert static_cast struct switch
template this thread_local throw true try typedef typeid typename union unsigned
using virtual void volatile wchar_t while xor xor_eq""".split())


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def identifier(text: str) -> str:
    text = text.replace("*", "_ptr_").replace("&", "_ref_").replace("~", "destructor_")
    text = re.sub(r"[^A-Za-z0-9_]+", "_", text).strip("_")
    if not text or text[0].isdigit() or text in CPP_KEYWORDS:
        text = "fn_" + text
    # Generated namespace members must not use C++ reserved double underscores.
    return re.sub(r"_+", "_", text)


def read_names(csv_bytes: bytes, image: bytes) -> list[dict]:
    rows = list(csv.DictReader(io.StringIO(csv_bytes.decode("utf-8-sig"))))
    accepted = []
    seen = set()
    image_sha = sha(image)
    for row in rows:
        confidence = row["confidence"]
        if confidence not in ("high", "medium", "low"):
            raise ValueError("Unknown confidence: " + confidence)
        if confidence == "low":
            continue
        address, size = int(row["xbox_address"], 16), int(row["size"])
        if address in seen or size <= 0 or address % 4 or size % 4:
            raise ValueError("Duplicate or invalid function range: " + row["xbox_address"])
        seen.add(address)
        if not BASE <= address < address + size <= BASE + len(image):
            raise ValueError("Function outside input image: " + row["xbox_address"])
        evidence = json.loads(row["evidence"])
        if evidence.get("xbox_image_sha256") != image_sha:
            raise ValueError("CSV evidence image SHA-256 differs from input image")
        name = row["name"]
        if "(" in name:
            if ")" not in name:
                raise ValueError("Unterminated function signature: " + name)
            stem, signature = name.split("(", 1)
            signature = signature[:-1] if signature.endswith(")") else signature
        else:
            # C exports such as png_read_row carry no demangled signature.
            stem, signature = name, None
        accepted.append({"address": address, "size": size, "name": name,
                         "confidence": confidence, "method": row["method"],
                         "evidence": evidence, "stem": identifier(stem),
                         "signature": signature})
    accepted.sort(key=lambda r: r["address"])
    stems = Counter(r["stem"] for r in accepted)
    identifiers = set()
    for row in accepted:
        result = row["stem"]
        if stems[result] > 1:
            if row["signature"] is None:
                raise ValueError("Ambiguous overload without signature: " + row["name"])
            result += "_" + identifier("sig_" + (row["signature"] or "void"))
        if result in identifiers:
            # Same normalized spelling (e.g. template punctuation) remains unique
            # by a suffix of the complete signature, never by input row order.
            result += "_sigsha_" + sha(row["name"].encode("utf-8"))[:12]
        if result in identifiers:
            raise ValueError("Duplicate exported name: " + row["name"])
        identifiers.add(result)
        row["identifier"] = result
    for left, right in zip(accepted, accepted[1:]):
        if left["address"] + left["size"] > right["address"]:
            raise ValueError("Overlapping CSV functions")
    return accepted


def evidence_text(row: dict) -> str:
    return row["method"] + "; " + json.dumps(row["evidence"]["signals"], ensure_ascii=True, sort_keys=True)


def header(rows: list[dict], hashes: dict) -> bytes:
    lines = ["// Generated by scripts/export_xbox_names.py; do not edit.",
             "// CSV SHA-256: " + hashes["csv"],
             "// Xbox image SHA-256: " + hashes["image"],
             "// Names are annotations, not host function pointers or an ABI.",
             "#pragma once", "", "#include <cstdint>", "", "namespace pvz::fn {"]
    for row in rows:
        lines.append("// " + row["name"])
        lines.append("inline constexpr std::uint32_t %s = 0x%08Xu; // %s: %s" % (
            row["identifier"], row["address"], row["confidence"], evidence_text(row)))
    lines += ["}  // namespace pvz::fn", ""]
    return "\n".join(lines).encode("utf-8")


GHIDRA_BODY = r'''
from ghidra.program.model.address import AddressSet
from ghidra.program.model.symbol import SourceType
import json

data = json.loads(PAYLOAD)
actual_sha = currentProgram.getExecutableSHA256()
if not actual_sha or actual_sha.lower() != data["hashes"]["image"]:
    raise RuntimeError("T02: executable SHA-256 mismatch; import the exact pvz-image.bin")
image_block = currentProgram.getMemory().getBlock(toAddr(0x82000000))
if image_block is None or image_block.getStart().getOffset() != 0x82000000:
    # BinaryLoader's block base is independent of Program.imageBase metadata.
    raise RuntimeError("T02: raw image block must start at 0x82000000")
if not currentProgram.getLanguage().isBigEndian():
    raise RuntimeError("T02: expected big-endian Xbox program")

manager = currentProgram.getFunctionManager()
memory = currentProgram.getMemory()
# Preflight every address before changing any name. Existing containing bodies
# are not silently split or deleted; the caller must review that discrepancy.
for row in data["functions"]:
    address = toAddr(row["address"])
    if not memory.contains(address) or not memory.contains(address.add(row["size"] - 1)):
        raise RuntimeError("T02: unmapped function: " + row["name"])
    containing = manager.getFunctionContaining(address)
    if containing is not None and containing.getEntryPoint() != address:
        raise RuntimeError("T02: another function contains " + row["name"])

transaction = currentProgram.startTransaction("T02 accepted names")
commit = False
created, renamed = 0, 0
try:
    for row in data["functions"]:
        monitor.checkCancelled()
        address = toAddr(row["address"])
        function = manager.getFunctionAt(address)
        before = str(function.getName()) if function is not None else "<none>"
        if function is None:
            body = AddressSet(address, address.add(row["size"] - 1))
            function = manager.createFunction(row["identifier"], address, body, SourceType.USER_DEFINED)
            created += 1
        elif before != row["identifier"]:
            function.setName(row["identifier"], SourceType.USER_DEFINED)
            renamed += 1
        old_comment = function.getComment() or ""
        # Preserve unrelated comments while replacing our own idempotent block.
        begin, end = "[T02-BEGIN]", "[T02-END]"
        if begin in old_comment:
            prefix, tail = old_comment.split(begin, 1)
            if end not in tail:
                raise RuntimeError("T02: unfinished prior comment block")
            old_comment = prefix + tail.split(end, 1)[1]
        comment = (begin + "\n" + row["name"] + "\nconfidence: " + row["confidence"] +
                   "\nevidence: " + row["evidence"] + "\nCSV SHA-256: " + data["hashes"]["csv"] +
                   "\nXbox image SHA-256: " + data["hashes"]["image"] + "\n" + end)
        function.setComment((old_comment.strip() + "\n\n" + comment).strip())
        println("T02_APPLIED 0x%08X %s -> %s [%s]" % (
            row["address"], before, str(function.getName()), row["confidence"]))
    commit = True
finally:
    currentProgram.endTransaction(transaction, commit)
println("T02_SUMMARY " + json.dumps({"csv_sha256": data["hashes"]["csv"],
    "image_sha256": actual_sha, "created": created, "renamed": renamed,
    "verified": len(data["functions"]), "project": str(currentProgram.getDomainFile())}, sort_keys=True))
'''


def ghidra(rows: list[dict], hashes: dict) -> bytes:
    functions = [{k: row[k] for k in ("address", "size", "name", "identifier", "confidence")}
                 | {"evidence": evidence_text(row)} for row in rows]
    payload = json.dumps({"hashes": hashes, "functions": functions}, ensure_ascii=True, sort_keys=True)
    source = ("# -*- coding: utf-8 -*-\n# Generated by scripts/export_xbox_names.py\n"
              "#@category PvZ.NativePort\n#@runtime Jython\n"
              "# CSV SHA-256: " + hashes["csv"] + "\n# Xbox image SHA-256: " + hashes["image"] +
              "\n# Import exact raw image at 0x82000000, then run this script.\n"
              "# Creates function bodies from CSV ranges; does not infer prototypes.\n"
              "PAYLOAD = " + repr(payload) + "\n" + GHIDRA_BODY)
    return source.encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=ROOT / "docs/native-port/data/xbox-names.csv")
    parser.add_argument("--image", type=Path, default=ROOT / ".cache/pvz-image.bin")
    parser.add_argument("--header", type=Path, default=ROOT / "src/xbox_names.h")
    parser.add_argument("--ghidra", type=Path, default=ROOT / "research/cross-platform/xbox-names.ghidra.py")
    parser.add_argument("--manifest", type=Path, default=ROOT / "research/cross-platform/xbox-names-export.json")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    csv_bytes, image = args.csv.read_bytes(), args.image.read_bytes()
    hashes = {"csv": sha(csv_bytes), "image": sha(image)}
    rows = read_names(csv_bytes, image)
    outputs = {args.header: header(rows, hashes), args.ghidra: ghidra(rows, hashes)}
    manifest = {"inputs": hashes, "exporter_sha256": sha(Path(__file__).read_bytes()),
                "confidence": dict(Counter(r["confidence"] for r in rows)),
                "functions": len(rows), "overloaded_members": [r["identifier"] for r in rows if "_sig_" in r["identifier"]],
                "outputs": {str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path): sha(content)
                            for path, content in outputs.items()}}
    outputs[args.manifest] = (json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != content:
                raise SystemExit("Outdated export: " + str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(json.dumps(manifest, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
